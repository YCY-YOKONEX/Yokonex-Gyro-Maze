      text(_mapKey(id, 'Desc'), {'value': fallback});

  String _mapKey(String id, String suffix) {
    const names = {
      'tide-corridor': 'tide',
      'ember-fault': 'ember',
      'moon-ice': 'moon',
      'crystal-circuit': 'crystal',
      'twilight-labyrinth': 'labyrinth',
      'oxide-reactor': 'reactor',
      'random': 'random',
      'custom': 'custom',
    };
    final key = id.startsWith('random-') ? 'random' : (names[id] ?? id);
    return '$key$suffix';
  }
